// Weekly readiness digest — PURE logic, no Forge calls, no email, no LLM.
// The digest is a plain-text/Markdown report (subject + body). Delivery is a
// Confluence page created by the scheduled trigger (src/trigger.js) — Forge
// has no outbound email, so the report lands where the team already works.
// All dates are evaluated in UTC so the weekday rule is timezone-independent.
import { trendLabel } from './history.js';

const MS_PER_DAY = 24 * 60 * 60 * 1000;
const MIN_GAP_DAYS = 6; // at most one digest per week

/** One stable identity per blocker, for diffing across weeks. */
export function blockerId(blk) {
  return `${blk.kind}:${blk.key}`;
}

/**
 * Diff two blocker lists (0.7.0, P1-8): which blockers are new since the
 * last digest, which are resolved, which persist. Pure, unit-tested.
 * @returns {{added: object[], resolved: object[], unchanged: object[]}}
 */
export function diffBlockers(previous, current) {
  const prev = new Map((previous ?? []).map((b) => [blockerId(b), b]));
  const cur = new Map((current ?? []).map((b) => [blockerId(b), b]));
  const added = [];
  const unchanged = [];
  for (const [id, b] of cur) {
    if (prev.has(id)) unchanged.push(b);
    else added.push(b);
  }
  const resolved = [];
  for (const [id, b] of prev) {
    if (!cur.has(id)) resolved.push(b);
  }
  return { added, resolved, unchanged };
}

/**
 * Should the weekly digest push Jira comments? (0.7.0, P1-11.)
 * Fires when the verdict dropped to BLOCKED or new blockers appeared —
 * never on a clean week, never twice for the same blockers (the caller
 * dedups by day, see pushedKeyFor in settings.js).
 * @param {object} opts { previousVerdict, currentVerdict, added: object[] }
 */
export function decidePush({ previousVerdict, currentVerdict, added }) {
  if (currentVerdict !== 'BLOCKED') return false;
  if (previousVerdict !== 'BLOCKED') return true; // verdict just dropped
  return (added ?? []).length > 0; // already BLOCKED, but new blockers appeared
}

/**
 * Build the weekly readiness report for one release.
 * @param {object} opts { projectKey, version, result, blockers, trend?, previousBlockers? }
 *   result is a scoreRelease() output; blockers is a collectBlockers() list;
 *   previousBlockers is the last digest's blocker list (for the new/resolved sections).
 * @returns {{subject:string, markdown:string}}
 */
export function buildDigest({ projectKey, version, result, blockers, trend, previousBlockers }) {
  if (!projectKey || typeof projectKey !== 'string' || projectKey.trim() === '') {
    throw new Error('buildDigest: projectKey is required');
  }
  if (!version || typeof version !== 'string' || version.trim() === '') {
    throw new Error('buildDigest: version is required');
  }
  if (!result || typeof result.score !== 'number' || !result.verdict) {
    throw new Error('buildDigest: result (scoreRelease output) is required');
  }
  const list = blockers ?? [];
  const b = result.breakdown ?? { blockers: 0, pullRequests: 0, issuesDone: 0, docs: 0 };
  const lines = [
    `# ShipCheck weekly readiness — ${projectKey} ${version}`,
    '',
    `**Score: ${result.score}/100 — ${result.verdict}**`,
    '',
    `Breakdown: Blockers ${b.blockers} · PRs ${b.pullRequests} · Issues ${b.issuesDone} · Docs ${b.docs} (of 100)`,
    '',
  ];
  if (trend && trend.direction !== 'none') lines.push(`Trend: ${trendLabel(trend)}`, '');
  lines.push('## Blockers', '');
  if (list.length === 0) {
    lines.push('No blockers. Ship it.', '');
  } else {
    for (const blk of list) lines.push(`- [${blk.kind}] ${blk.key}: ${blk.summary}`);
    lines.push('');
  }
  // 0.7.0 (P1-8): what changed since the last digest. previousBlockers
  // comes from the last digest's stored blocks; absent on the first run.
  if (previousBlockers) {
    const diff = diffBlockers(previousBlockers, list);
    lines.push('## New blockers since last week', '');
    if (diff.added.length === 0) lines.push('None.', '');
    else { for (const blk of diff.added) lines.push(`- [${blk.kind}] ${blk.key}: ${blk.summary}`); lines.push(''); }
    lines.push('## Resolved since last week', '');
    if (diff.resolved.length === 0) lines.push('None.', '');
    else { for (const blk of diff.resolved) lines.push(`- [${blk.kind}] ${blk.key}: ${blk.summary}`); lines.push(''); }
  }
  lines.push('## Warnings', '');
  const warnings = result.warnings ?? [];
  if (warnings.length === 0) {
    lines.push('None.', '');
  } else {
    for (const w of warnings) lines.push(`- ${w}`);
    lines.push('');
  }
  lines.push('---', '', 'Generated by ShipCheck (rule-based readiness, no LLM).');
  const diff = previousBlockers ? diffBlockers(previousBlockers, list) : null;
  return {
    subject: `ShipCheck weekly readiness — ${projectKey} ${version}: ${result.verdict} (${result.score}/100)`,
    markdown: lines.join('\n'),
    // Structured form for the Confluence ADF render (digestToAdf) — same data,
    // no second source of truth.
    blocks: {
      score: result.score,
      verdict: result.verdict,
      breakdown: b,
      blockers: list.map((blk) => ({ ...blk })),
      warnings: [...warnings],
      trendLabel: trend && trend.direction !== 'none' ? trendLabel(trend) : null,
      addedBlockers: diff ? diff.added.map((blk) => ({ ...blk })) : null,
      resolvedBlockers: diff ? diff.resolved.map((blk) => ({ ...blk })) : null,
    },
  };
}

/**
 * Render a buildDigest() result as Atlassian Document Format (ADF) JSON,
 * for creating the digest page in Confluence via REST. Pure string building.
 */
export function digestToAdf(digest) {
  const b = digest?.blocks;
  if (!b) throw new Error('digestToAdf: digest.blocks is required (use buildDigest output)');
  const text = (t) => ({ type: 'text', text: t });
  const para = (t) => ({ type: 'paragraph', content: [text(t)] });
  const heading = (level, t) => ({ type: 'heading', attrs: { level }, content: [text(t)] });
  const bullets = (items) => ({
    type: 'bulletList',
    content: items.map((i) => ({ type: 'listItem', content: [para(i)] })),
  });
  const content = [
    heading(1, digest.subject),
    para(`Score: ${b.score}/100 — ${b.verdict}`),
    para(`Breakdown: Blockers ${b.breakdown.blockers} · PRs ${b.breakdown.pullRequests} · Issues ${b.breakdown.issuesDone} · Docs ${b.breakdown.docs} (of 100)`),
  ];
  if (b.trendLabel) content.push(para(`Trend: ${b.trendLabel}`));
  content.push(heading(2, 'Blockers'));
  content.push(b.blockers.length === 0
    ? para('No blockers. Ship it.')
    : bullets(b.blockers.map((blk) => `[${blk.kind}] ${blk.key}: ${blk.summary}`)));
  // 0.7.0 (P1-8): new/resolved sections when the digest was built with a
  // previous blocker list (null on the first run — no section rendered).
  if (b.addedBlockers) {
    content.push(heading(2, 'New blockers since last week'));
    content.push(b.addedBlockers.length === 0
      ? para('None.')
      : bullets(b.addedBlockers.map((blk) => `[${blk.kind}] ${blk.key}: ${blk.summary}`)));
  }
  if (b.resolvedBlockers) {
    content.push(heading(2, 'Resolved since last week'));
    content.push(b.resolvedBlockers.length === 0
      ? para('None.')
      : bullets(b.resolvedBlockers.map((blk) => `[${blk.kind}] ${blk.key}: ${blk.summary}`)));
  }
  content.push(heading(2, 'Warnings'));
  content.push(b.warnings.length === 0 ? para('None.') : bullets(b.warnings));
  content.push(para('Generated by ShipCheck (rule-based readiness, no LLM).'));
  return JSON.stringify({ type: 'doc', version: 1, content });
}

/**
 * Should the digest fire right now?
 * @param {object} settings { digestEnabled, digestDay (0=Sun..6=Sat, UTC), projectKey, version }
 * @param {Date} now
 * @param {string|null} lastSentAt ISO timestamp of the last digest sent (null = never)
 * @returns {boolean}
 */
export function shouldSendDigest(settings, now, lastSentAt) {
  if (!settings || settings.digestEnabled !== true) return false;
  const day = settings.digestDay;
  if (!Number.isInteger(day) || day < 0 || day > 6) return false;
  if (!settings.projectKey || !settings.version) return false;
  if (now.getUTCDay() !== day) return false;
  if (lastSentAt) {
    const last = new Date(lastSentAt);
    if (!Number.isNaN(last.getTime()) && now.getTime() - last.getTime() < MIN_GAP_DAYS * MS_PER_DAY) {
      return false;
    }
  }
  return true;
}
