/** Saved language (per browser), default English. */
export function getLang() {
  try {
    if (typeof localStorage === 'undefined') return DEFAULT_LANG;
    const lang = localStorage.getItem(STORAGE_KEY);
    return SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

/** Persist the language; returns the language actually in effect. */
export function setLang(lang) {
  const next = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Sandboxed iframe without storage: the switch still works for this view.
  }
  return next;
}

/** Look a key up, substituting {vars}; falls back to English, then the key. */
export function t(key, vars = {}, lang = getLang()) {
  const dict = STRINGS[lang] ?? STRINGS.en;
  let s = dict[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Apply the current language to every static string in the document. */
export function applyI18n(lang = getLang()) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang === 'zh-CN' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n, {}, lang);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder, {}, lang);
  });
}
